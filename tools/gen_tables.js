#!/usr/bin/env node
// preview/clock-core.js(규칙의 정본) 에서 두 가지를 만든다.
// 1) firmware/hangul_clock/clock_tables.h : 펌웨어가 쓰는 칸 번호 표
// 2) tests/golden.txt : 하루 1,440분 × 경계 설정 여러 가지의 정답표 (C++ 검사가 견준다)
// D4: 규칙을 손으로 두 번 쓰지 않는다. JS 판을 고치면 이 도구를 다시 돌린다.
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const H = require(path.join(root, 'preview', 'clock-core.js'));

const word = (cells, name) => {
  if (!cells) return '{0, {0, 0}}';
  if (cells.length > 2) throw new Error(`${name}: 칸이 2개를 넘는다`);
  const c = cells.concat([0, 0]).slice(0, 2);
  return `{${cells.length}, {${c[0]}, ${c[1]}}}`;
};
const series = (obj, from, to, name) => {
  const out = [];
  for (let i = 0; i <= to; i++) out.push(i < from ? word(null) : word(obj[i], `${name}[${i}]`));
  return out.join(', ');
};

const W = H.W;
const hdr = `// Auto-generated by tools/gen_tables.js from preview/clock-core.js. Do not edit by hand.
// 판: ${H.GRID.join(' / ')}
#pragma once
#include <stdint.h>

namespace hc {

struct Word { uint8_t n; uint8_t cell[2]; };
struct Bounds { uint8_t morning, day, evening, night; bool noon; };

static const int GRID_N = ${H.N};
static const int CELL_COUNT = ${H.CELLS.length};
// 때: 0 아침, 1 낮, 2 저녁, 3 밤
static const Word W_PERIOD[4] = { ${[W.morning, W.day, W.evening, W.night].map((c, i) => word(c, 'period' + i)).join(', ')} };
static const Word W_HOUR[13] = { ${series(W.hour, 1, 12, 'hour')} };   // [1]..[12]
static const Word W_SI = ${word(W.si, 'si')};
static const Word W_NOON = ${word(W.noon, 'noon')};
static const Word W_TENS[6] = { ${series(W.tens, 2, 5, 'tens')} };     // [2]..[5]
static const Word W_SIP = ${word(W.sip, 'sip')};
static const Word W_UNIT[10] = { ${series(W.unit, 1, 9, 'unit')} };    // [1]..[9]
static const Word W_BUN = ${word(W.bun, 'bun')};
static const Bounds DEFAULT_BOUNDS = { ${H.DEF.morning}, ${H.DEF.day}, ${H.DEF.evening}, ${H.DEF.night}, ${H.DEF.noon ? 'true' : 'false'} };

}  // namespace hc
`;
// 공개판(아이폰만)에는 firmware · tests 폴더가 없다. 폴더가 있을 때만 쓴다(2026-11-26).
const writeIfDir = (file, text) => { if (fs.existsSync(path.dirname(file))) fs.writeFileSync(file, text); };
writeIfDir(path.join(root, 'firmware', 'hangul_clock', 'clock_tables.h'), hdr);

// 정답표: 기본값, 정오 끔, 그리고 경계의 양 끝 값들
const sets = [Object.assign({}, H.DEF), Object.assign({}, H.DEF, { noon: false })];
for (const a of [3, 8]) for (const d of [9, 13]) for (const e of [16, 19]) for (const n of [20, 23]) sets.push({ morning: a, day: d, evening: e, night: n, noon: true });
const lines = [];
for (const o of sets) {
  const key = `${o.morning} ${o.day} ${o.evening} ${o.night} ${o.noon ? 1 : 0}`;
  for (let h = 0; h < 24; h++) for (let m = 0; m < 60; m++) {
    const lit = H.lit(h, m, o).map(c => `${c.i}:${c.kind}`).join(',');
    lines.push(`${key} ${h} ${m} ${lit}`);
  }
}
writeIfDir(path.join(root, 'tests', 'golden.txt'), lines.join('\n') + '\n');

// 아이폰(I2): Swift 표와 Swift 시험용 정답표. 정답표는 git 에서 빠진다(.gitignore).
const swArr = a => `[${a.join(', ')}]`;
const swList = (obj, from, to) => {
  const out = [];
  for (let i = 0; i <= to; i++) out.push(i < from ? '[]' : swArr(obj[i]));
  return `[${out.join(', ')}]`;
};
const swift = `// Auto-generated by tools/gen_tables.js from preview/clock-core.js. Do not edit by hand.
// 판: ${H.GRID.join(' / ')}
public enum ClockTables {
    public static let grid: [String] = [${H.CELLS.map(c => `"${c}"`).join(', ')}]
    /// 때: 0 아침, 1 낮, 2 저녁, 3 밤
    public static let period: [[Int]] = [${[W.morning, W.day, W.evening, W.night].map(swArr).join(', ')}]
    /// [1]...[12], [0] 은 빈칸
    public static let hour: [[Int]] = ${swList(W.hour, 1, 12)}
    public static let si: [Int] = ${swArr(W.si)}
    public static let noon: [Int] = ${swArr(W.noon)}
    /// [2]...[5]
    public static let tens: [[Int]] = ${swList(W.tens, 2, 5)}
    public static let sip: [Int] = ${swArr(W.sip)}
    /// [1]...[9]
    public static let unit: [[Int]] = ${swList(W.unit, 1, 9)}
    public static let bun: [Int] = ${swArr(W.bun)}
    public static let defaultMorning = ${H.DEF.morning}
    public static let defaultDay = ${H.DEF.day}
    public static let defaultEvening = ${H.DEF.evening}
    public static let defaultNight = ${H.DEF.night}
    public static let defaultNoon = ${H.DEF.noon ? 'true' : 'false'}
}
`;
const kit = path.join(root, 'ios', 'HangulClockKit');
const coreDir = path.join(kit, 'Sources', 'HangulClockCore');
const resDir = path.join(kit, 'Tests', 'HangulClockCoreTests', 'Golden');
fs.mkdirSync(coreDir, { recursive: true });
fs.mkdirSync(resDir, { recursive: true });
fs.writeFileSync(path.join(coreDir, 'ClockTables.swift'), swift);
fs.writeFileSync(path.join(resDir, 'golden.txt'), lines.join('\n') + '\n');
const sentences = [];
for (let h = 0; h < 24; h++) for (let m = 0; m < 60; m++) sentences.push(`${h} ${m} ${H.sentence(h, m, H.DEF)}`);
fs.writeFileSync(path.join(resDir, 'golden_sentences.txt'), sentences.join('\n') + '\n');

console.log(`clock_tables.h 를 썼다. golden.txt ${lines.length}줄 (설정 ${sets.length}가지 × 1,440분)`);
console.log(`ClockTables.swift 를 썼다. Swift 정답표 ${lines.length}줄, 문장 ${sentences.length}줄`);
